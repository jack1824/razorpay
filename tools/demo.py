"""`make demo` — drive the demo timeline so the presenter talks instead of clicking.

    python -m tools.demo [--base-url ...] [--no-kill] [--restore] [--dry-run]

Beats 1 through 6 run on the schedule in `data/seed/timeline.json`, which is generated by
`tools/gen_seed.py` and is the same file the seed fixtures come from. **Beat 7 (MCP) stays
manual** — it is the one worth pausing on, and a pause is a decision the presenter makes.

── Every expectation is CHECKED, and a mismatch is loud ────────────────────────────────

The timeline carries `expect`, `expect_rule`, `expect_risk_score` and
`expect_risk_score_non_null`. This runner asserts all four and prints a red MISMATCH line
when the system does something other than what the script says, then exits non-zero at the
end.

That is the point of running it before the demo rather than during. A runner that printed
the timeline's expectations instead of the system's answers would be a very expensive way to
read a JSON file — and it is exactly the failure mode `make eval` was built to avoid, one
screen over. Nothing here is hardcoded: every line printed is what the API returned.

── The rolling windows are reset first, and that is not tidiness ───────────────────────

A second run inside the observation TTL produces DIFFERENT results, and the first time this
runner was run twice in a row the warm-up beat and the drift beat swapped verdicts: the
warm-up scored 0.67 and stepped up, and the drift — arriving on top of a window that already
contained one — scored 0.08 and was allowed. Nothing was broken. The agent's history is
shared state, and the drift became the agent's normal.

That is the same defect class as F-040: an outcome that depends on ambient state, which does
not fail so much as wait for someone to run it at the wrong moment. On stage the wrong moment
is the second rehearsal.

So the demo agents' windows are cleared before the run, which makes each run start from the
same behavioural state and makes the timeline mean what it says. `--keep-windows` skips it,
for when the question is specifically what a warm agent looks like.

── A run SPENDS, and the preflight says so before it starts ────────────────────────────

The ledger is append-only and a demo run consumes real budget from the seeded mandates. It
does not reset, and it must not: a tool that credited budget back so its own script would
pass is a tool that has stopped testing the thing it claims to demonstrate.

After enough runs the cumulative cap is reached and beat 3.0 — an ordinary ₹475 purchase —
denies with `mandate.max_total`. Which is correct enforcement and a confusing demo, and it
is a confusing demo that appears on the eighth rehearsal rather than the first.

So the run is preflighted: what each mandate will spend against what it has left, refused up
front with the command to reset. The failure is legible instead of arriving as a wrong
verdict in the middle of a beat.

── Beat 6 is destructive, and reversible ───────────────────────────────────────────────

The tamper is a real superuser UPDATE against a committed record, because the control being
demonstrated is detection by cryptography and not prevention by the database. It therefore
leaves `make verify` reporting FAIL afterwards — permanently, which is correct and is also
a footgun on a laptop you have to demo from twice.

So the original value is written to `data/demo/last_tamper.json` and `--restore` puts it
back. Restoring is the same superuser UPDATE in reverse: we are undoing our own tamper by
exactly the means we made it, which is honest rather than a special case.
"""

